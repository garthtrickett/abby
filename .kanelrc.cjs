const { makeKyselyHook } = require("kanel-kysely");

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is required for Kanel generation");
}

/** @type {import('kanel').Config} */
module.exports = {
  connection: { connectionString: process.env.DATABASE_URL },
  schemas: ["public"],
  typeFilter: (pgType) => pgType.kind !== "function" && pgType.kind !== "procedure" &&
    !["kysely_migration", "kysely_migration_lock"].includes(pgType.name.toLowerCase()),
  outputPath: "./src/storage/generated",
  preDeleteOutputFolder: true,
  tsModuleFormat: "esm",
  preRenderHooks: [makeKyselyHook()],
  postRenderHooks: [
    (path, lines) => [
      "// @generated",
      "// This file is automatically generated by Kanel. Do not modify manually.",
      "",
      ...(path.endsWith("Database.ts")
        ? lines.map(line => line === "export default Database;" ? "export type { Database as default };" : line)
        : lines),
    ],
  ],
};
